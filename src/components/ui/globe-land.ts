function inRing(lng: number, lat: number, ring: Ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i],
      [xj, yj] = ring[j];
    if (yi > lat !== yj > lat && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

/** True when the point (degrees) falls on land in the simplified map. */
export function isLand(lat: number, lng: number) {
  return LAND.some((r) => inRing(lng, lat, r)) && !WATER.some((r) => inRing(lng, lat, r));
}
